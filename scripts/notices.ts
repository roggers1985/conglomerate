// Third-party notices (ADR 0027): the license texts of the packages the plugin's bundles inline, generated from
// Bun's build metadata and the packages' own files, so the notices can't fall behind the bundles.

import path from "node:path";
import { z } from "zod";
import { JSON_BYTES_MAX, readDir, readJson, readText, TEXT_BYTES_MAX } from "../lib/files.ts";
import { parse } from "../lib/parse.ts";
import type { GeneratedFiles } from "./generated.ts";

/** The generated notices file in the plugin's root folder, next to the plugin's own `LICENSE`. */
export const NOTICES_FILE = "THIRD-PARTY-NOTICES.md";

/** A bundled package's license, as it appears in the notices. */
export type PackageNotice = {
    readonly name: string;
    readonly version: string;
    readonly license: string;
    readonly licenseText: string;
    /** The bundles (file names in `dist/`) that inline this package. */
    readonly bundles: readonly string[];
};

// Someone else's format, so extra fields are allowed (ADR 0020).
const PackageJsonSchema = z.looseObject({
    version: z.string().min(1).max(100),
    license: z
        .string({ error: "is required: a bundled package must declare its license" })
        .min(1, "is required: a bundled package must declare its license")
        .max(200),
});

const LICENSE_FILE = /^licen[cs]e(\.(md|txt))?$/i;
const PACKAGE_FILES_MAX = 1_000; // the top level of an installed package; most have a dozen entries

/**
 * Reads a bundled package's version, license and license text from its installed files.
 *
 * @param name - The package name, e.g. `zod`.
 * @param options.nodeModulesDir - The `node_modules` folder the package was bundled from.
 * @param options.bundles - The bundles that inline it.
 * @param options.signal - Cancels the reads.
 * @returns The package's notice.
 * @throws Error when the package declares no license or ships no license file, because its notice can't be
 * generated then.
 * @throws DOMException named `AbortError` when `signal` aborts.
 *
 * @example
 * ```ts
 * const notice = await readPackageNotice("zod", {
 *     nodeModulesDir: `${process.cwd()}/node_modules`,
 *     bundles: ["checkups.js"],
 *     signal: AbortSignal.timeout(5_000),
 * });
 *
 * expect(notice.license).toBe("MIT");
 * expect(notice.licenseText).toStartWith("MIT License");
 * ```
 */
export async function readPackageNotice(
    name: string,
    {
        nodeModulesDir,
        bundles,
        signal,
    }: { readonly nodeModulesDir: string; readonly bundles: readonly string[]; readonly signal: AbortSignal },
): Promise<PackageNotice> {
    const dir = path.join(nodeModulesDir, name);
    const manifest = parse(
        PackageJsonSchema,
        await readJson(path.join(dir, "package.json"), { maxBytes: JSON_BYTES_MAX, signal }),
    );

    if (manifest.kind === "invalid") {
        throw new Error(`${name}/package.json: ${manifest.errors.join("; ")}`);
    }

    const entries = await readDir(dir, { maxEntries: PACKAGE_FILES_MAX, signal });
    const licenseFile = entries.map((entry) => entry.name).find((fileName) => LICENSE_FILE.test(fileName));

    if (licenseFile === undefined) {
        throw new Error(`${name} ships no LICENSE file, so its notice can't be generated`);
    }

    const licenseText = await readText(path.join(dir, licenseFile), { maxBytes: TEXT_BYTES_MAX, signal });

    return {
        name,
        version: manifest.value.version,
        license: manifest.value.license,
        licenseText: licenseText.trim(),
        bundles,
    };
}

function renderNotice(notice: PackageNotice): string {
    const bundles = notice.bundles.map((bundle) => `\`dist/${bundle}\``).join(", ");

    return [
        `## ${notice.name} ${notice.version} (${notice.license})`,
        "",
        `Bundled into ${bundles}.`,
        "",
        "~~~text",
        notice.licenseText,
        "~~~",
    ].join("\n");
}

/**
 * Renders the third-party notices of the plugin's bundles.
 *
 * @param notices - One notice per bundled package, in the order they should appear.
 * @returns The contents of `THIRD-PARTY-NOTICES.md`.
 *
 * @example
 * ```ts
 * const notices = renderThirdPartyNotices([
 *     { name: "zod", version: "4.6.5", license: "MIT", licenseText: "MIT License\n…", bundles: ["checkups.js"] },
 * ]);
 *
 * expect(notices).toContain("## zod 4.6.5 (MIT)\n\nBundled into `dist/checkups.js`.");
 * expect(notices).toContain("~~~text\nMIT License\n…\n~~~");
 * ```
 */
export function renderThirdPartyNotices(notices: readonly PackageNotice[]): string {
    const intro = [
        "# Third-party notices",
        "",
        "Generated by `bun run generate` from the bundles' build metadata and the packages' own files (ADR 0027). Do not edit by hand.",
        "",
        "The plugin's scripts are bundled into `dist/` (ADR 0020). Bundling inlines third-party code without its license",
        "files, so their notices are carried here.",
    ];
    const sections = notices.length === 0 ? ["No third-party code is bundled."] : notices.map(renderNotice);

    return [...intro, "", sections.join("\n\n"), ""].join("\n");
}

/**
 * Renders the plugin's generated legal files: its own `LICENSE` (copied from the repository root, because only the
 * plugin folder is distributed) and the third-party notices of its bundles.
 *
 * @param options.repositoryRoot - The repository's root folder, with `LICENSE` and `node_modules`.
 * @param options.packages - The bundled packages and their bundles, from `renderBundles`.
 * @param options.signal - Cancels the reads.
 * @returns File name → content, for the plugin's root folder.
 * @throws Error when a bundled package has no license or no license file.
 * @throws DOMException named `AbortError` when `signal` aborts.
 *
 * @example
 * ```ts
 * const files = await renderLegalFiles({
 *     repositoryRoot: process.cwd(),
 *     packages: new Map([["zod", ["checkups.js"]]]),
 *     signal: AbortSignal.timeout(5_000),
 * });
 *
 * expect([...files.keys()]).toEqual(["LICENSE", "THIRD-PARTY-NOTICES.md"]);
 * expect(files.get("LICENSE")).toStartWith("MIT License");
 * ```
 */
export async function renderLegalFiles({
    repositoryRoot,
    packages,
    signal,
}: {
    readonly repositoryRoot: string;
    readonly packages: ReadonlyMap<string, readonly string[]>;
    readonly signal: AbortSignal;
}): Promise<GeneratedFiles> {
    const nodeModulesDir = path.join(repositoryRoot, "node_modules");
    const [license, notices] = await Promise.all([
        readText(path.join(repositoryRoot, "LICENSE"), { maxBytes: TEXT_BYTES_MAX, signal }),
        Promise.all(
            [...packages].map(([name, bundles]) => readPackageNotice(name, { nodeModulesDir, bundles, signal })),
        ),
    ]);

    return new Map([
        ["LICENSE", license],
        [NOTICES_FILE, renderThirdPartyNotices(notices)],
    ]);
}
